from prometheus_client import Counter, Gauge, Histogram



# Agent metrics

AGENT_RUNS_TOTAL = Counter(
    "agent_runs_total",
    "Total number of agent runs",
)

AGENT_ACTIVE_RUNS = Gauge(
    "agent_active_runs",
    "Number of currently active agent runs",
)

AGENT_RUN_DURATION = Histogram(
    "agent_run_duration_seconds",
    "Time spent executing an agent run",
)


AGENT_RUN_FAILURES_TOTAL = Counter(
    "agent_run_failures_total",

    "Total number of agent runs that raised an unhandled error",
)

# LLM metrics

LLM_CALLS_TOTAL = Counter(
    "llm_calls_total",
    "Total number of LLM calls",
)

LLM_CALL_DURATION = Histogram(
    "llm_call_duration_seconds",
    "Time spent on LLM calls",
)

LLM_INPUT_TOKENS_TOTAL = Counter(
    "llm_input_tokens_total",
    "Total number of input tokens sent to the LLM",
)

LLM_OUTPUT_TOKENS_TOTAL = Counter(
    "llm_output_tokens_total",
    "Total number of output tokens generated by the LLM",
)

# Tool metrics

TOOL_CALLS_TOTAL = Counter(
    "tool_calls_total",
    "Total number of tool calls",
    ["tool_name","tool_type"]
)

TOOL_CALL_DURATION = Histogram(
    "tool_call_duration_seconds",
    "Time spent executing tools",
    ["tool_name","tool_type"]
)

TOOL_SUCCESS_TOTAL = Counter(
    "tool_success_total",
    "Total number of successful tool calls",
    ["tool_name","tool_type"]
)

TOOL_FAILURE_TOTAL = Counter(
    "tool_failure_total",
    "Total number of failed tool calls",
    ["tool_name","tool_type"]
)

# Memory metrics

MEMORY_OPERATIONS_TOTAL = Counter(
    "memory_operations_total",
    "Total number of memory operations",
)

MEMORY_RETRIEVAL_DURATION = Histogram(
    "memory_retrieval_duration_seconds",
    "Time spent retrieving memories",
)

# Permissions

PERMISSION_DECISIONS_TOTAL = Counter(
    "permission_decisions_total",
    "Total number of permission decisions",
    ["tool_name", "tool_type", "decision"]
)

PERMISSION_CHECK_DURATION = Histogram(
    "permission_check_duration_seconds",
    "Time spent evaluating a permission decision",
    ["tool_name", "tool_type"]
)

# Planner

PLANNER_DURATION = Histogram(
    "planner_duration_seconds",
    "Time spent in planner operations",
    ["operation"]
)

PLANNER_ERRORS_TOTAL = Counter(
    "planner_errors_total",
    "Total number of planner operations that failed",
    ["operation"]
)

# LLM errors
# (LLM_CALLS_TOTAL / LLM_CALL_DURATION above cover volume and latency;
# this covers the failure case, which nothing previously recorded.)

LLM_ERRORS_TOTAL = Counter(
    "llm_errors_total",
    "Total number of LLM calls that raised an error",
    ["component"]
)

# Sub-agents
# ("sub-agent" = a scheduled task re-run through Agent.run() by the
# TaskScheduler; subagent_type is a fixed, low-cardinality label, never
# the task text itself.)

SUBAGENT_RUNS_TOTAL = Counter(
    "subagent_runs_total",
    "Total number of sub-agent runs",
    ["subagent_type"]
)

SUBAGENT_ACTIVE_RUNS = Gauge(
    "subagent_active_runs",
    "Number of currently active sub-agent runs",
)

SUBAGENT_RUN_DURATION = Histogram(
    "subagent_run_duration_seconds",
    "Time spent executing a sub-agent run",
    ["subagent_type"]
)

SUBAGENT_FAILURES_TOTAL = Counter(
    "subagent_failures_total",
    "Total number of sub-agent runs that failed",
    ["subagent_type"]
)